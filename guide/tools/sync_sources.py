"""Embed exact local Python excerpts and figures for offline reading.
Run from any directory: python guide/tools/sync_sources.py
No third-party Python packages required. Never modifies the original scripts.
"""
from pathlib import Path
from datetime import date
import ast, hashlib, json, re, shutil

GUIDE=Path(__file__).resolve().parents[1]
ROOT=GUIDE.parent
files={}
snippets={}
for path in sorted((ROOT/"code").glob("0[1-5]_*.py")):
    key=path.name[:2]
    source=path.read_text(encoding="utf-8")
    lines=source.splitlines()
    files[key]={"name":path.name,"text":source,"sha256":hashlib.sha256(path.read_bytes()).hexdigest(),"lines":len(lines)}
    tree=ast.parse(source)
    for node in tree.body:
        if isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef)):
            snippets[f"{key}:{node.name}"]={"file":key,"start":node.lineno,"end":node.end_lineno}

def span(key,name,start,end):
    lines=files[key]["text"].splitlines()
    starts=[i for i,l in enumerate(lines) if l.startswith(start)]
    if len(starts)!=1: raise ValueError((key,name,"start",starts,start))
    a=starts[0]
    matches=[i for i in range(a,len(lines)) if lines[i].startswith(end)]
    if not matches: raise ValueError((key,name,"end missing",end))
    snippets[f"{key}:{name}"]={"file":key,"start":a+1,"end":matches[0]+1}

span("01","gd_loop","# --- Batch GD","w_gd = w")
span("01","sgd_loop","# --- SGD","w_sgd = w")
span("01","mb_loop","# --- Mini-batch","w_mb = w")
span("03","init","    rng = np.random.default_rng(seed)","    tong_tg = 0.0")
span("03","loop","    for epoch in range(epochs):","        ls_thoi_gian.append(tong_tg)")
span("03","data","rng = np.random.default_rng(42)","J_cx = mat_mat(")
span("04","regressor",'sgd = SGDRegressor(', 'ols = LinearRegression()')
span("04","classifier",'clf = SGDClassifier(', 'clf.fit(')
span("04","partial",'model = SGDClassifier(', '    acc_online.append(')
span("04","mlp",'for b, lr0, mau in ', '    mlp.fit(')
span("05","data",'sc = StandardScaler()', 'ham_mat_mat = nn.CrossEntropyLoss()')
span("05","init",'    torch.manual_seed(seed)', '    loader = DataLoader(')
span("05","loop",'    for _ in range(epochs):', '            optimizer.step()')
span("05","eval",'        with torch.no_grad():', '            ls_acc.append(')
used=re.findall(r'data-snippet="([^"]+)"',(GUIDE/"index.html").read_text(encoding="utf-8"))
assert all(k in snippets for k in used), [k for k in used if k not in snippets]
for value in snippets.values():
    f=files[value["file"]]
    value["code"]="\n".join(f["text"].splitlines()[value["start"]-1:value["end"]])
payload={"synced":date.today().isoformat(),"files":files,"snippets":snippets}
(GUIDE/"sources.js").write_text("// Generated by tools/sync_sources.py; do not edit excerpts by hand.\nwindow.GUIDE_SOURCES = "+json.dumps(payload,ensure_ascii=False,indent=2)+";\n",encoding="utf-8")
(GUIDE/"assets").mkdir(exist_ok=True)
for name in ["hinh1_learning_rate.png","hinh4_mat_mat.png","hinh7_pytorch_mlp.png"]:
    shutil.copy2(ROOT/"hinh"/name,GUIDE/"assets"/name)
print(f"Embedded {len(files)} files; {len(used)} referenced excerpts, {len(snippets)} available excerpts; copied 3 figures.")

